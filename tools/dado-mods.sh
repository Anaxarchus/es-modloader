#!/bin/sh
# Build tool for the Dado loader's mods and tests. Needs the Dado toolchain
# (`dado`, `dadoc`) on PATH; building a mod needs esbuild (or npx). See README.md.
#
#   dado-mods.sh harness <outdir>      emit the harness as <outdir>/esmod.c and esmod.h
#   dado-mods.sh sdk                   regenerate sdk/es/game.dado from the harness
#   dado-mods.sh mod <dir> [out.js]    build a mod (a directory holding one .dados class extending
#                                      es.Mod) into one .js file
#   dado-mods.sh examples              build the examples, and every example and test mod into
#                                      the in-game test's scripts (tests/ingame/scripts)
#   dado-mods.sh plugin <dir>          assemble the examples as a plugin (<dir>/scripts/*.js)
#   dado-mods.sh test                  run every example and test mod through the built loader
#                                      in a fake host ($ESDADO_LIB, or the library in build/)
set -eu

# IDEs often run builds without the shell's PATH; add where Homebrew and Dado install.
PATH="$PATH:$HOME/.local/bin:$HOME/dado:/opt/homebrew/bin:/usr/local/bin"
HERE=$(cd "$(dirname "$0")/.." && pwd)         # the loader's repository
die() { echo "dado-mods: $*" >&2; exit 1; }
command -v dado >/dev/null 2>&1 || die "dado is not on PATH (install: https://dadolang.com)"
command -v dadoc >/dev/null 2>&1 || die "dadoc is not on PATH"
COLLECTIONS=$(dado where --no-update-check | sed -n 's/^collections=//p')
CC=${CC:-cc}
TRIPLE=$($CC -dumpmachine)
DADOC="dadoc --collections=$COLLECTIONS"

emit_harness() {
	out=$1
	mkdir -p "$out"
	for phase in c h; do
		$DADOC --package --library --target="$TRIPLE" --emit=$phase -o "$out/esmod.$phase" "$HERE/harness/entry.dado"
	done
	cmake -DFILE="$out/esmod.c" -P "$HERE/tools/fix-max-align.cmake"
}

# esbuild flattens a mod's library build (its class, es.Mod and the parts of the
# Dado runtime it uses) into the single import-free file the loader loads.
run_esbuild() {
	if [ -n "${ESBUILD:-}" ]; then "$ESBUILD" "$@"
	elif command -v esbuild >/dev/null 2>&1; then esbuild "$@"
	elif command -v npx >/dev/null 2>&1; then npx --yes esbuild@0.24.0 "$@"
	else die "building a mod needs esbuild: install Node (which brings npx), or esbuild itself, or set ESBUILD"
	fi
}

build_mod() {
	dir=${1%/}
	[ -d "$dir" ] || die "a mod is a directory holding one .dados file: $dir"
	[ -n "$(ls "$dir"/*.dados 2>/dev/null)" ] || die "no .dados file in $dir"
	# A mod may span several files; its entry is the class that extends es.Mod.
	src=$(grep -l '^class [A-Za-z_][A-Za-z0-9_]* extends es\.Mod' "$dir"/*.dados 2>/dev/null | head -n 1)
	[ -n "$src" ] || src=$(ls "$dir"/*.dados | head -n 1)
	class=$(sed -n 's/^class \([A-Za-z_][A-Za-z0-9_]*\).*/\1/p' "$src" | head -n 1)
	[ -n "$class" ] || die "$src has no \`class Name extends es.Mod\` header"
	out=${2:-$dir/$(basename "$dir").js}
	lib=$(mktemp -d)
	# The mod as a JavaScript library: one module per class, with its own copy of the runtime.
	if ! $DADOC --import=sdk="$HERE/sdk" --emit=js-package --package -o "$lib" "$src"; then
		rm -rf "$lib"; exit 1
	fi
	entry=$(ls "$lib"/*/"$class.js" 2>/dev/null | grep -v "^$lib/es/" | head -n 1)
	[ -n "$entry" ] || { rm -rf "$lib"; die "dadoc wrote no module for class $class"; }
	# Run from the library folder, so the file comments esbuild writes name
	# paths inside it and not the temporary folder: the same mod builds the same file.
	case $out in /*) ;; *) out=$(pwd)/$out ;; esac
	(cd "$lib" && run_esbuild "${entry#"$lib"/}" --bundle --format=esm --log-level=warning --outfile="$out") || { rm -rf "$lib"; exit 1; }
	rm -rf "$lib"
	echo "built $out"
}

# The built loader: $ESDADO_LIB, or the one in build/.
loader_lib() {
	if [ -n "${ESDADO_LIB:-}" ]; then echo "$ESDADO_LIB"; return; fi
	for f in "$HERE"/build/libesdado.so "$HERE"/build/libesdado.dylib; do
		[ -f "$f" ] && { echo "$f"; return; }
	done
	die "no built loader: build it (cmake -B build && cmake --build build) or set ESDADO_LIB"
}

case ${1:-} in
harness)
	[ $# -eq 2 ] || die "usage: dado-mods.sh harness <outdir>"
	emit_harness "$2" ;;
sdk)
	tmp=$(mktemp)
	$DADOC --package --library --emit=script-api -o "$tmp" "$HERE/harness/entry.dado"
	mkdir -p "$HERE/sdk/es"
	{
		echo "// The Endless Sky mod SDK: the \`Game\` a mod is handed, as declarations."
		echo "// Generated by \`tools/dado-mods.sh sdk\` from harness/Game.dados;"
		echo "// do not edit. Mods import the SDK as \`import \"imports:sdk/es\"\` and receive"
		echo "// the game's real Game at run time. Mod.dados and version.dado are written by hand."
		echo
		sed -e '1,/^package /{/^\/\//d}' -e 's/^package api$/package es/' "$tmp"
	} > "$HERE/sdk/es/game.dado"
	rm -f "$tmp"
	echo "wrote $HERE/sdk/es/game.dado" ;;
mod)
	[ $# -ge 2 ] || die "usage: dado-mods.sh mod <dir> [out.js]"
	build_mod "$2" "${3:-}" ;;
examples)
	scripts="$HERE/tests/ingame/scripts"
	mkdir -p "$scripts"
	# Examples keep their built .js beside their source; the in-game test's
	# plugin gets the examples and the test mods.
	for d in "$HERE"/examples/*; do
		[ -n "$(ls "$d"/*.dados 2>/dev/null)" ] || continue
		name=$(basename "$d")
		build_mod "$d" "$d/$name.js"
		cp "$d/$name.js" "$scripts/$name.js"
	done
	for d in "$HERE"/tests/mods/*; do
		build_mod "$d" "$scripts/$(basename "$d").js"
	done ;;
plugin)
	[ $# -eq 2 ] || die "usage: dado-mods.sh plugin <dir>"
	# examples/plugin holds the plugin's plugin.txt and data files; the mods are built into its scripts folder.
	mkdir -p "$2/scripts"
	cp -R "$HERE/examples/plugin/." "$2/"
	for d in "$HERE"/examples/*; do
		[ -n "$(ls "$d"/*.dados 2>/dev/null)" ] || continue
		build_mod "$d" "$2/scripts/$(basename "$d").js"
	done
	echo "assembled the example plugin in $2" ;;
test)
	loader=$(loader_lib)
	work=$(mktemp -d "${TMPDIR:-/tmp}/esdado-test.XXXXXX")
	[ -n "${KEEP:-}" ] || trap 'rm -rf "$work"' EXIT
	# Every EsHost function must be set in the fake host's table.
	missing=0
	fields=0
	for field in $(sed -n '/^typedef struct EsHost {/,/^} EsHost;/p' "$HERE/include/es_api.h" \
			| sed -n 's/.*(\(ES_CALL \)\{0,1\}\*\([a-z_0-9]*\))(.*/\2/p'); do
		fields=$((fields + 1))
		grep -q "host\.$field = " "$HERE/tests/fake_host.cpp" || { echo "FAIL: fake_host.cpp does not set EsHost::$field"; missing=1; }
	done
	[ "$missing" = 0 ] || exit 1
	echo "fake host: sets all $fields EsHost functions"
	${CXX:-c++} -std=c++17 -O1 -Wall -Wextra -I"$HERE/include" "$HERE/tests/fake_host.cpp" \
		$( [ "$(uname)" = Darwin ] || echo -ldl ) -o "$work/fake_host"
	# The sources, in the game's order: resources, then the plugins.
	cp -R "$HERE/tests/sources/." "$work/"
	for d in "$HERE"/examples/* "$HERE"/tests/mods/*; do
		[ -n "$(ls "$d"/*.dados 2>/dev/null)" ] || continue
		build_mod "$d" "$work/Test Mods/scripts/$(basename "$d").js" >/dev/null
	done
	"$work/fake_host" "$loader" "$work/resources" "$work/Test Mods" "$work/Zipped.zip" "$work/Override"
	# The watchdog's timing: a short hook limit after a long load limit, and the reverse.
	for limits in "2000 250" "300 1000"; do
		echo "== watchdog, load and hook limits (ms): $limits"
		# shellcheck disable=SC2086
		"$work/fake_host" --watchdog "$loader" $limits "$HERE/tests/sources-watchdog/Watchdog"
	done ;;
*)
	sed -n '2,14p' "$0" | sed 's/^# \{0,1\}//'
	exit 2 ;;
esac
